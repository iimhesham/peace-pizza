function saveNiyaba2Verdict(){
  const who=document.getElementById("niyaba2VerdictWho");
  const story=document.getElementById("niyaba2VerdictStory");
  const chips=document.querySelectorAll("#niyaba2VerdictWhy input:checked");
  if(!who||!story)return;
  const data={
    who:who.value,
    story:story.value,
    why:Array.from(chips).map(c=>c.value)
  };
  try{localStorage.setItem("niyaba2Verdict",JSON.stringify(data));}catch(e){}
  const savedBox=document.getElementById("niyaba2VerdictSaved");
  if(savedBox){
    savedBox.textContent="محفوظ ✓";
    clearTimeout(window._niyaba2VerdictTimer);
    window._niyaba2VerdictTimer=setTimeout(()=>{savedBox.textContent="";},1500);
  }
}

function loadNiyaba2Verdict(){
  let data=null;
  try{data=JSON.parse(localStorage.getItem("niyaba2Verdict")||"null");}catch(e){}
  if(!data)return;
  const who=document.getElementById("niyaba2VerdictWho");
  const story=document.getElementById("niyaba2VerdictStory");
  if(who)who.value=data.who||"";
  if(story)story.value=data.story||"";
  document.querySelectorAll("#niyaba2VerdictWhy input").forEach(c=>{
    c.checked=(data.why||[]).includes(c.value);
  });
}
document.addEventListener("DOMContentLoaded",loadNiyaba2Verdict);
