(function renderTrainIntro(){
  const box=document.getElementById("trainIntroText");
  if(!box)return;
  const mk=(tag,cls,txt)=>{const e=document.createElement(tag);if(cls)e.className=cls;if(txt!==undefined)e.textContent=txt;return e;};

  const facts=mk("div","tr-facts");
  TRAIN_FACTS.forEach(([k,v])=>{
    const f=mk("div","tr-fact");
    f.append(mk("small","",k),mk("b","",v));
    facts.appendChild(f);
  });
  box.appendChild(facts);

  TRAIN_STORY_PARTS.forEach((p,i)=>{
    const sec=mk("div","tr-part");
    sec.append(mk("span","tr-no",String(i+1)),mk("h3","",p.h),mk("p","",p.t));
    box.appendChild(sec);
  });

  box.appendChild(mk("p","tr-closer",TRAIN_STORY_CLOSER));

  const note=mk("div","tr-note");
  note.append(mk("b","","ملحوظة اختيارية"),mk("span","",TRAIN_STORY_NOTE));
  box.appendChild(note);
})();
