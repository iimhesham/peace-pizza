function saveNiyabaVerdict(){
  const who=document.getElementById("niyabaVerdictWho");
  const story=document.getElementById("niyabaVerdictStory");
  const chips=document.querySelectorAll("#niyabaVerdictWhy input:checked");
  if(!who||!story)return;
  const data={
    who:who.value,
    story:story.value,
    why:Array.from(chips).map(c=>c.value)
  };
  try{localStorage.setItem("niyabaVerdict",JSON.stringify(data));}catch(e){}
  const savedBox=document.getElementById("niyabaVerdictSaved");
  if(savedBox){
    savedBox.textContent="محفوظ ✓";
    clearTimeout(window._niyabaVerdictTimer);
    window._niyabaVerdictTimer=setTimeout(()=>{savedBox.textContent="";},1500);
  }
}

function loadNiyabaVerdict(){
  let data=null;
  try{data=JSON.parse(localStorage.getItem("niyabaVerdict")||"null");}catch(e){}
  if(!data)return;
  const who=document.getElementById("niyabaVerdictWho");
  const story=document.getElementById("niyabaVerdictStory");
  if(who)who.value=data.who||"";
  if(story)story.value=data.story||"";
  document.querySelectorAll("#niyabaVerdictWhy input").forEach(c=>{
    c.checked=(data.why||[]).includes(c.value);
  });
}
document.addEventListener("DOMContentLoaded",loadNiyabaVerdict);
loadNiyabaVerdict();

